/** t('online_now', {n: 3}) -> "3 online" in the current language */
export function t(key, vars) {
  let s = (DICT[current] && DICT[current][key]) ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}

/** Error code from the server -> text in the user's language (falls back to the server's message) */
export function errText(err) {
  const k = `e_${err && err.code}`;
  const known = (DICT[current] && DICT[current][k]) ?? en[k];
  return known || (err && err.message) || t('e_server');
}

